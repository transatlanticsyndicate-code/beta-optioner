// ЗАЧЕМ: единое правило применения тумблера «Учитывать дивиденды» к дивидендной доходности.
// Дивидендная доходность влияет на цену опциона в модели Black-Scholes-Merton (для колла
// её рост цену снижает, для пута — повышает). Раньше в разных местах калькулятора эта логика
// дублировалась вручную (`useDividends ? dividendYield : 0`), и в части мест «сырое» значение
// уходило в расчёт в обход тумблера. Вынесено сюда в чистую функцию, чтобы гарантировать
// одинаковое поведение везде и покрыть его unit-тестами независимо от React-компонента.

/**
 * Приводит «сырое» значение дивидендной доходности к валидному числу >= 0.
 * Источник (API /api/polygon/dividend-yield) может вернуть null/undefined при незагруженных
 * данных, NaN при парсинге, либо (в теории) отрицательное значение — ни один из этих случаев
 * не должен попадать в модель как есть.
 */
function sanitizeDividendYield(dividendYield) {
  if (typeof dividendYield !== 'number' || !Number.isFinite(dividendYield)) {
    return 0;
  }
  return dividendYield > 0 ? dividendYield : 0;
}

/**
 * Возвращает доходность, которую фактически нужно подставлять в расчёт модели или
 * передавать в дочерние компоненты, с учётом состояния тумблера «Учитывать дивиденды».
 * Тумблер выключен → всегда 0, независимо от того, что реально загружено.
 * Тумблер включён → санитизированное значение (мусор/отрицательное → 0).
 */
export function resolveDividendYield(useDividends, dividendYield) {
  if (!useDividends) {
    return 0;
  }
  return sanitizeDividendYield(dividendYield);
}

/**
 * Предикат для предупреждения в UI: тумблер выключен, но у актива реально есть
 * ненулевая дивидендная доходность — расчёт систематически смещён (завышает цену
 * коллов / занижает цену путов). Не блокирует выключение тумблера, только сигнализирует
 * пользователю о последствии его выбора.
 */
export function shouldWarnDividendsIgnored(useDividends, dividendYield) {
  if (useDividends) {
    return false;
  }
  return sanitizeDividendYield(dividendYield) > 0;
}

export { sanitizeDividendYield };
