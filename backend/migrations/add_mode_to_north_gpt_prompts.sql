-- Миграция (PostgreSQL / prod): добавить колонку `mode` в таблицу north_gpt_prompts
-- ЗАЧЕМ: Три изолированных набора промптов стратегии «Север GPT» — по одному на
-- режим работы: «Актив + опционы» (with_asset), «Только опционы» (options_only),
-- «Только CALL» (call_only). В форме подбора видны только промпты выбранного режима.
--
-- Решение: ВСЕ существующие промпты попадают в набор 'options_only' — это режим
-- по умолчанию, в котором библиотека и наполнялась до появления разделения.
-- Нужные промпты пользователь скопирует в другие режимы кнопкой «Сохранить как новый».
--
-- ВАЖНО про порядок выката: миграция обратно совместима (старый код колонку просто
-- не видит, INSERT'ы проходят благодаря DEFAULT), а вот новый код без колонки падает
-- с 500 на всех эндпоинтах промптов. Поэтому: СНАЧАЛА миграция, ПОТОМ деплой бэкенда.
-- Дублирующая страховка есть в app/database.py (init_db добавляет колонку при старте,
-- если её нет) — но полагаться только на неё не стоит.
--
-- Для локального SQLite использовать add_mode_to_north_gpt_prompts_sqlite.sql:
-- SQLite не понимает `ADD COLUMN IF NOT EXISTS`.

-- 1. Добавить колонку. DEFAULT 'options_only' сразу проставляет значение всем
--    существующим строкам — отдельный backfill не требуется.
ALTER TABLE north_gpt_prompts
  ADD COLUMN IF NOT EXISTS mode VARCHAR(20) NOT NULL DEFAULT 'options_only';

-- 2. Страховка на случай, если колонка уже существовала с пустыми значениями.
UPDATE north_gpt_prompts
   SET mode = 'options_only'
 WHERE mode IS NULL OR mode = '';

-- 3. Индекс на mode — по нему идёт выборка набора при каждом открытии формы.
--    Имя ровно такое, какое даёт SQLAlchemy для index=True, чтобы на пересозданной
--    с нуля базе не появился второй индекс с другим именем.
CREATE INDEX IF NOT EXISTS ix_north_gpt_prompts_mode
  ON north_gpt_prompts (mode);

